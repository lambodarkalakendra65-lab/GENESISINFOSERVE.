export function getInitialLeads(): LeadRecord[] {
  return SEED_DATA.map((item) => {
    const verification = verifyContactDetails({
      phone: item.p,
      email: item.email,
      companyName: item.n,
      city: item.city,
    });

    const lead: LeadRecord = {
      id: item.id,
      n: item.n,
      a: item.a,
      city: item.city,
      t: item.t,
      p: item.p,
      p2: item.p2,
      c: item.c,
      source: item.source,
      email: item.email,
      cn: item.cn,
      cnDesignation: item.cnDesignation,
      requirements: item.requirements,
      budgetEst: item.budgetEst,
      dp: item.dp || [],
      pr: item.dp || [],
      assignedToUserId: item.assignedToUserId,
      assignedToUserName: item.assignedToUserName,
      verification,
      res: '',
      next: '',
      note: '',
      mailsSentCount: 0,
      lastUpdated: new Date().toISOString(),
    };

    return lead;
  });
}
